// Bundles the rewind-search agent skill into one self-contained file, and (optionally) exports the
// demo index as a ready-to-use example: node scripts/build-skill.mjs [--export-demo <out.rewind.json>]
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import * as esbuild from 'esbuild';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const skill = path.join(root, 'skills', 'rewind-search');

await esbuild.build({
  entryPoints: [path.join(skill, 'src', 'cli.js')],
  outfile: path.join(skill, 'scripts', 'search.mjs'),
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: ['node20'],
  external: ['@huggingface/transformers'], // optional: used for embeddings only when installed
  banner: { js: '// Generated by scripts/build-skill.mjs from skills/rewind-search/src/cli.js — do not edit.' },
  logLevel: 'warning',
});
console.log('Built skills/rewind-search/scripts/search.mjs');

const i = process.argv.indexOf('--export-demo');
if (i > 0) {
  const { exportIndex } = await import('../src/core/exchange.js');
  const { loadDemoIndex } = await import('../eval/common.mjs');
  const { DEFAULT_MODEL } = await import('../src/core/config.js');
  const out = path.resolve(process.argv[i + 1]);
  await fs.mkdir(path.dirname(out), { recursive: true });
  await fs.writeFile(out, JSON.stringify(exportIndex(await loadDemoIndex(DEFAULT_MODEL))));
  console.log(`Exported demo index to ${path.relative(root, out)}`);
}
